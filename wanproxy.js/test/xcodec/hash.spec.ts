function parseKatHex(hex: string): bigint[] {
  const values: bigint[] = [];
  for (let offset = 0; offset < hex.length; offset += 16) {
    values.push(BigInt(`0x${hex.slice(offset, offset + 16)}`));
  }
  return values;
}

describe("XCodecHash", () => {
  it("matches the C++ single-byte known-answer tests", () => {
    const expected = parseKatHex(CHAR_KAT_HEX);
    expect(expected).toHaveLength(256);

    for (const [byte, hash] of expected.entries()) {
      expect(
        XCodecHash.hashSegment(
          new Uint8Array(XCODEC_SEGMENT_LENGTH).fill(byte),
        ),
      ).toBe(hash);
    }
  });

  it("hashSegment matches incremental add", () => {
    const segment = Uint8Array.from(
      { length: XCODEC_SEGMENT_LENGTH },
      (_, index) => (index * 17) & 0xff,
    );
    const hash = new XCodecHash();
    for (const byte of segment) {
      hash.add(byte);
    }

    expect(hash.mix()).toBe(XCodecHash.hashSegment(segment));
  });

  it("rolling hash matches fresh recomputation", () => {
    const data = Uint8Array.from(
      { length: XCODEC_SEGMENT_LENGTH + 64 },
      (_, index) => (index * 29 + 7) & 0xff,
    );
    const hash = new XCodecHash();
    for (const byte of data.subarray(0, XCODEC_SEGMENT_LENGTH)) {
      hash.add(byte);
    }

    for (let index = XCODEC_SEGMENT_LENGTH; index < data.length; index += 1) {
      const byte = data[index];
      expect(byte).toBeDefined();
      if (byte !== undefined) {
        hash.roll(byte);
      }
      expect(hash.mix()).toBe(
        XCodecHash.hashSegment(
          data.subarray(index - XCODEC_SEGMENT_LENGTH + 1, index + 1),
        ),
      );
    }
  });

  it("rejects invalid hash states and bytes", () => {
    const hash = new XCodecHash();
    expect(() => hash.mix()).toThrow(RangeError);
    expect(() => hash.roll(1)).toThrow(RangeError);
    expect(() => hash.add(256)).toThrow(RangeError);
    expect(() => hash.add(1.5)).toThrow(RangeError);
    expect(() => XCodecHash.hashSegment(new Uint8Array(1))).toThrow(RangeError);

    for (let index = 0; index < XCODEC_SEGMENT_LENGTH; index += 1) {
      hash.add(0);
    }
    expect(() => hash.add(0)).toThrow(RangeError);
    hash.reset();
    expect(() => hash.mix()).toThrow(RangeError);
  });
});
